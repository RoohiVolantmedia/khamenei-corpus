_PUNCT_RE = re.compile(r'[،؛؟!«»()\[\]{}.:,\-_/\\،۰-۹0-9]+')
_DIAC_RE = re.compile(r'[ً-ٰ]')
_DIGIT_RE = re.compile(r'^[\d۰-۹]+$')
_LATIN_RE = re.compile(r'^[a-zA-Z]+$')
_TATWEEL_RE = re.compile(r'^[ـ\-_]+$')
# کاراکترهای نامرئی که در پیکره به جای نیم‌فاصله (U+200C) استفاده شده‌اند
# U+200F = RLM، U+00AD = soft hyphen، U+200B = zero width space،
# U+200E = LRM، U+FEFF = BOM
_INVIS_RE = re.compile(r'[‏­​‎﻿]')
# چند نیم‌فاصله‌ی پشت‌هم → یکی
_MULTI_ZWNJ_RE = re.compile(r'‌{2,}')


def normalize_fa(text: str) -> str:
    """نرمال‌سازی متن فارسی: یکسان‌سازی کاراکترها و حذف اعراب.

    علاوه بر یکسان‌سازی حروف عربی/فارسی، کاراکترهای نامرئی جایگزین نیم‌فاصله
    را به U+200C استاندارد تبدیل می‌کند تا فرم‌های مختلف «می‌شود»، «می‌کند» و
    مشابه‌ها به شکل یکسان در FA_STOP فیلتر شوند.
    """
    # یکسان‌سازی حروف عربی/فارسی
    # 'ي' U+064A = Arabic ya، 'ى' U+0649 = Arabic alef maqsura — هر دو → ی U+06CC
    t = text.replace('ي', 'ی').replace('ى', 'ی').replace('ك', 'ک').replace('ة', 'ه')
    # حذف اعراب (تنوین، کسره، فتحه، ضمه و ...)
    t = _DIAC_RE.sub('', t)
    # جایگزینی کاراکترهای نامرئی با نیم‌فاصله‌ی استاندارد
    t = _INVIS_RE.sub('‌', t)
    # چند نیم‌فاصله‌ی متوالی → یکی
    t = _MULTI_ZWNJ_RE.sub('‌', t)
    return t


def tokenize(text: str) -> list:
    """توکن‌سازی متن فارسی با فیلتر واژگان توقف"""
    if not text:
        return []
    t = normalize_fa(text)
    t = _PUNCT_RE.sub(' ', t)
    tokens = t.split()
    result = []
    for tok in tokens:
        # حذف نیم‌فاصله‌های ابتدا/انتهای توکن (مثل «برای‌» یا «‌است»)
        tok = tok.strip('‌')
        if len(tok) < 2:
            continue
        if tok in FA_STOP:
            continue
        if _DIGIT_RE.match(tok):
            continue
        if _LATIN_RE.match(tok):
            continue
        if _TATWEEL_RE.match(tok):
            continue
        result.append(tok)
    return result


def is_built() -> bool:
    """بررسی وجود جدول word_freq و داشتن ردیف"""
    try:
        conn = sqlite3.connect(DB_PATH)
        cur = conn.execute(
            "SELECT name FROM sqlite_master WHERE type='table' AND name='word_freq'"
        )
        if cur.fetchone() is None:
            conn.close()
            return False
        cur = conn.execute("SELECT COUNT(*) FROM word_freq")
        count = cur.fetchone()[0]
        conn.close()
        return count > 0
    except Exception:
        return False


def build_index(progress_callback=None) -> dict:
    """
    ساخت جدول word_freq از کل پیکره.
    Schema: word_freq(word TEXT PRIMARY KEY, total_freq INT, doc_freq INT)
    Schema: corpus_meta(key TEXT PRIMARY KEY, value TEXT)
    """
    conn = sqlite3.connect(DB_PATH)
    conn.execute("PRAGMA journal_mode=WAL")

    # ساخت جداول
    conn.execute("DROP TABLE IF EXISTS word_freq")
    conn.execute("DROP TABLE IF EXISTS corpus_meta")
    conn.execute("""
        CREATE TABLE word_freq (
            word TEXT PRIMARY KEY,
            total_freq INT,
            doc_freq INT
        )
    """)
    conn.execute("""
        CREATE TABLE corpus_meta (
            key TEXT PRIMARY KEY,
            value TEXT
        )
    """)
    conn.commit()

    # شمارش کل اسناد
    total_docs = conn.execute("SELECT COUNT(*) FROM documents").fetchone()[0]

    word_total: Counter = Counter()
    word_doc: Counter = Counter()
    total_tokens = 0

    batch_size = 500
    offset = 0
    processed = 0

    while True:
        rows = conn.execute(
            "SELECT doc_id, full_text FROM documents LIMIT ? OFFSET ?",
            (batch_size, offset)
        ).fetchall()
        if not rows:
            break

        for doc_id, full_text in rows:
            if not full_text:
                continue
            tokens = tokenize(full_text)
            total_tokens += len(tokens)
            doc_counter = Counter(tokens)
            word_total.update(doc_counter)
            word_doc.update(doc_counter.keys())

        processed += len(rows)
        offset += batch_size

        if progress_callback is not None:
            progress_callback(processed, total_docs)

        # درج دسته‌ای هر 5000 سند برای کاهش مصرف حافظه
        if processed % 5000 == 0:
            _flush_counters(conn, word_total, word_doc)
            word_total.clear()
            word_doc.clear()

    # درج باقیمانده
    _flush_counters(conn, word_total, word_doc)

    # ذخیره متادیتا
    conn.execute(
        "INSERT OR REPLACE INTO corpus_meta (key, value) VALUES (?, ?)",
        ('total_tokens', str(total_tokens))
    )
    conn.execute(
        "INSERT OR REPLACE INTO corpus_meta (key, value) VALUES (?, ?)",
        ('total_docs', str(total_docs))
    )
    conn.commit()

    unique_words = conn.execute("SELECT COUNT(*) FROM word_freq").fetchone()[0]
    conn.close()

    return {
        'total_docs': total_docs,
        'total_tokens': total_tokens,
        'unique_words': unique_words,
    }


def _flush_counters(conn, word_total: Counter, word_doc: Counter) -> None:
    """درج یا به‌روزرسانی شمارش‌ها در جدول word_freq"""
    if not word_total:
        return
    data = []
    for word, tf in word_total.items():
        df = word_doc.get(word, 0)
        data.append((word, tf, df))

    conn.executemany("""
        INSERT INTO word_freq (word, total_freq, doc_freq) VALUES (?, ?, ?)
        ON CONFLICT(word) DO UPDATE SET
            total_freq = total_freq + excluded.total_freq,
            doc_freq   = doc_freq   + excluded.doc_freq
    """, data)
    conn.commit()


def get_total_tokens() -> int:
    """خواندن تعداد کل توکن‌ها از corpus_meta"""
    try:
        conn = sqlite3.connect(DB_PATH)
        row = conn.execute(
            "SELECT value FROM corpus_meta WHERE key='total_tokens'"
        ).fetchone()
        conn.close()
        if row:
            return int(row[0])
        return 0
    except Exception:
        return 0


def get_word_freq(words: list) -> dict:
    """
    جستجوی دسته‌ای بسامد واژگان.
    بازمی‌گرداند: {word: (total_freq, doc_freq)}
    """
    if not words:
        return {}
    try:
        conn = sqlite3.connect(DB_PATH)
        placeholders = ','.join('?' * len(words))
        rows = conn.execute(
            f"SELECT word, total_freq, doc_freq FROM word_freq WHERE word IN ({placeholders})",
            list(words)
        ).fetchall()
        conn.close()
        return {row[0]: (row[1], row[2]) for row in rows}
    except Exception:
        return {}


def get_tfidf_stopwords(max_doc_freq_pct: float = 0.15) -> frozenset:
    """
    واژه‌هایی که در بیش از max_doc_freq_pct درصد از اسناد ظاهر می‌شوند
    را به‌عنوان stop word برمی‌گرداند — این‌ها کلماتی هستند که آن‌قدر
    عمومی‌اند که هیچ قدرت تمایزی ندارند.

    منطق: IDF پایین = در اسناد زیاد ظاهر می‌شود = بی‌معنی در تحلیل keyness/collocation

    مثال با max_doc_freq_pct=0.15:
      واژه‌ای که در ۱۵٪+ اسناد (>۶,۴۰۰ سند از ۴۲,۷۴۹) ظاهر شود فیلتر می‌شود.
    """
    try:
        conn = sqlite3.connect(DB_PATH)
        # تعداد کل اسناد
        row = conn.execute("SELECT value FROM corpus_meta WHERE key='total_docs'").fetchone()
        if not row:
            conn.close()
            return frozenset()
        total_docs = int(row[0])
        threshold = int(total_docs * max_doc_freq_pct)
        # واژه‌هایی که doc_freq بیش از آستانه دارند
        rows = conn.execute(
            "SELECT word FROM word_freq WHERE doc_freq > ?",
            (threshold,)
        ).fetchall()
        conn.close()
        return frozenset(r[0] for r in rows)
    except Exception:
        return frozenset()
